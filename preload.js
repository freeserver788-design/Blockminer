const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bm', {
  gpu:    () => ipcRenderer.invoke('gpu:stats'),
  power:  (w, i) => ipcRenderer.invoke('power:set', w, i),
  powerAll: (w) => ipcRenderer.invoke('power:setAll', w),
  powerReset: (i) => ipcRenderer.invoke('power:reset', i),
  pickMiner: () => ipcRenderer.invoke('miner:pick'),
  start:  (p) => ipcRenderer.invoke('miner:start', p),
  stop:   () => ipcRenderer.invoke('miner:stop'),
  downloadMiner: () => ipcRenderer.invoke('miner:download'),
  downloadGpuMiner: () => ipcRenderer.invoke('miner:downloadLol'),
  testPool: (pool) => ipcRenderer.invoke('pool:test', pool),
  loadCfg: () => ipcRenderer.invoke('config:load'),
  saveCfg: (c) => ipcRenderer.invoke('config:save', c),
  prices: () => ipcRenderer.invoke('prices:fetch'),
  dcInit:  (o) => ipcRenderer.invoke('dc:init', o),
  dcStatus: (s) => ipcRenderer.invoke('dc:status', s),
  dcStop:  () => ipcRenderer.invoke('dc:stop'),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  dcReady: (cb) => ipcRenderer.on('dc:ready', (_e, d) => cb(d)),
  dcError: (cb) => ipcRenderer.on('dc:error', (_e, d) => cb(d)),
  dcConnecting: (cb) => ipcRenderer.on('dc:connecting', () => cb()),
  isAdmin: () => ipcRenderer.invoke('sys:admin'),
  elevate: () => ipcRenderer.invoke('sys:elevate'),
  sys:    () => ipcRenderer.invoke('sys:info'),
  wdReset:   () => ipcRenderer.invoke('wd:reset'),
  guardState: () => ipcRenderer.invoke('guard:state'),
  onMainToast: (cb) => ipcRenderer.on('main:toast', (_e, d) => cb(d)),
  updateCheck:    () => ipcRenderer.invoke('update:check'),
  updateDownload: (url) => ipcRenderer.invoke('update:download', url),
  updateInstall:  (installerPath) => ipcRenderer.invoke('update:install', installerPath),
  updateOpen:     (url) => ipcRenderer.invoke('update:open', url),
  onLog:  (cb) => ipcRenderer.on('miner:log', (_e, d) => cb(d)),
  onStop: (cb) => ipcRenderer.on('miner:stopped', () => cb()),
  onStart: (cb) => ipcRenderer.on('miner:started', (_e, d) => cb(d || {})),
  onData: (cb) => ipcRenderer.on('gpu:data', (_e, d) => cb(d)),
  donateStatus: () => ipcRenderer.invoke('donate:status'),
});
