let __lang = 'de';

window.BM_I18N = {
  setLang(l) { __lang = (l === 'en') ? 'en' : 'de'; },
  get lang() { return __lang; },
  has(key) { return (I18N.de[key] != null) || (I18N.en[key] != null); },
  t(key, vars) {
    let s = (I18N[__lang] && I18N[__lang][key] != null) ? I18N[__lang][key] : (I18N.de[key] != null ? I18N.de[key] : key);
    if (vars) { for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k])); }
    return s;
  },
  applyStatic() {
    document.title = BM_I18N.t('app.title');
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const val = BM_I18N.t(el.getAttribute('data-i18n'));
      if (el.tagName === 'INPUT') { el.placeholder = val; return; }
      el.innerHTML = val;
    });
  },
};
